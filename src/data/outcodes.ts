export function extractOutcode(postcode: string): string | null {
  const normalised = postcode.trim().toUpperCase().replace(/\s+/g, ' ');
  const match = normalised.match(/^([A-Z]{1,2}\d{1,2}[A-Z]?)\s*\d[A-Z]{2}$/i)
    ?? normalised.match(/^([A-Z]{1,2}\d{1,2}[A-Z]?)$/i);
  return match ? match[1].toUpperCase() : null;
}
